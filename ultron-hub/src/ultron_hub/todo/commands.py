"""`ultron-hub todo ...` subcommands.

Every command prints one JSON object on stdout:
    {"status": "ok"|"error", "command": "todo.<name>", "summary": str, "data": obj|null, "error": str|null}
"""

import argparse
import json
import logging
import os
import re
from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

from ultron_hub.common.errors import InvalidRequestError
from ultron_hub.common.settings import Settings
from ultron_hub.esprit import etat
from ultron_hub.esprit import store as journal
from ultron_hub.todo import closing, links, service, summarizer
from ultron_hub.todo.service import (
    EmptyTitleError, NotesTooLongError, TitleTooLongError, resolve_title,
)
from ultron_hub.todo.store import NATURES, STATUSES, TodoStore, downgrade_to_v2


log = logging.getLogger(__name__)

SQUAD_SUBJECT_ENV = "ULTRON_ESCOUADE_SUJET"  # formerly set by the squad engine (retired, todo #458); still read if present
BOARD_FILTERS = ("open", "urgent", "closed", "fond", "done_today")  # done_today: the dashboard's briefing (todo #270)
BOARD_LIMIT = 1000
CLOSED_LIMIT = 30


def envelope(command: str, status: str = "ok", summary: str = "", data: Any = None,
             error: str | None = None) -> dict[str, Any]:
    return {"status": status, "command": f"todo.{command}", "summary": summary, "data": data, "error": error}


def add_parser(sub: argparse._SubParsersAction, parser_class: type) -> None:
    todo = sub.add_parser("todo", help="manage the todo list")
    cmds = todo.add_subparsers(dest="todo_command", required=True, parser_class=parser_class)

    add = cmds.add_parser("add", help="add a task")
    add.add_argument("--title", required=True)
    add.add_argument("--priority", default="normal", help="high|normal|low (haute|normale|basse)")
    add.add_argument("--category", default=None, help="one of todo.categories (default: the first)")
    add.add_argument("--due", default=None, help="today|tomorrow|week|none|+Nd|YYYY-MM-DD")
    add.add_argument("--notes", default="")
    add.add_argument("--source", default="cli", help="e.g. telegram, agent:hermes, import")
    add.add_argument("--nature", default=None, help="chantier|fond (default: fond, chantier inside a squad)")
    add.add_argument("--chantier", default=None,
                     help=f"an existing subject (~/notes/prompt/<s>.md); default: ${SQUAD_SUBJECT_ENV} inside a squad, else none")
    add.add_argument("--clair", default=None, help="one line (140 chars max) saying what the task is for; "
                     "generated by haiku when absent")
    long_group = add.add_mutually_exclusive_group()
    long_group.add_argument("--long", dest="title_mode", action="store_const", const="summarize",
                            help="generate a short title with LLM when title exceeds 60 chars")
    long_group.add_argument("--truncate", dest="title_mode", action="store_const", const="truncate",
                            help="truncate title to 60 chars when it exceeds the limit")

    ls = cmds.add_parser("list", help="list tasks")
    ls.add_argument("--status", default="todo", help=f"{'|'.join(STATUSES)}|all")
    ls.add_argument("--category", default=None)
    ls.add_argument("--limit", type=int, default=50)
    ls.add_argument("--nature", default=None, help="|".join(NATURES))
    _filter_chantier(ls)

    for name, helptext in (("show", "show a task and its history"), ("done", "mark as done"),
                           ("reopen", "mark as todo again"), ("cancel", "cancel a task")):
        p = cmds.add_parser(name, help=helptext)
        p.add_argument("id", type=int)
        if name in ("done", "cancel"):
            p.add_argument("--i-am-human", dest="human", action="store_true",
                           help="at a real terminal: type back a code to confirm (refused for agents)")

    close_auto = cmds.add_parser("close-auto", help="close a todo merged alone and verified (by auto:verifie, todo #528); "
                                                    "refused otherwise")
    close_auto.add_argument("id", type=int)

    livree = cmds.add_parser("livree", help="say a task is done without code: it shows in À toi for the user's ✅ "
                                            "(closes nothing)")
    livree.add_argument("id", type=int)
    livree.add_argument("--note", default="", help="one line, 200 characters max")

    edit = cmds.add_parser("edit", help="edit fields of a task")
    edit.add_argument("id", type=int)
    edit.add_argument("--title")
    edit.add_argument("--priority")
    edit.add_argument("--category")
    edit.add_argument("--due")
    edit.add_argument("--notes")
    edit.add_argument("--nature", help="|".join(NATURES))
    edit.add_argument("--clair", help="empty string clears it")
    edit_chantier = edit.add_mutually_exclusive_group()
    edit_chantier.add_argument("--chantier", help="an existing subject (~/notes/prompt/<s>.md)")
    edit_chantier.add_argument("--sans-chantier", dest="sans_chantier", action="store_true",
                               help="take the task out of its chantier")
    edit.add_argument("--by", default="cli", help="who asks, kept in the nature event (e.g. telegram-button)")

    digest = cmds.add_parser("digest", help="daily summary (overdue, today, high priority)")
    digest.add_argument("--send", action="store_true", help="deliver it with the common sending point (`envoi`)")

    cmds.add_parser("meta", help="allowed priorities, categories and due shortcuts (for menus)")

    board = cmds.add_parser("board", help="Telegram list: sorted tasks with branch markers and counts")
    board.add_argument("--filter", default="open", choices=BOARD_FILTERS)
    board.add_argument("--category", default=None)
    _filter_chantier(board)

    rattacher = cmds.add_parser("rattacher", help="file the open todos in their chantiers (proposal, then apply)")
    mode = rattacher.add_mutually_exclusive_group(required=True)
    mode.add_argument("--proposer", action="store_true", help="print the changes and their fingerprint")
    mode.add_argument("--appliquer", metavar="H8", help="apply the proposal with this fingerprint (refused if changed)")
    rattacher.add_argument("--by", default="cli", help="who asks, kept in each chantier event")

    retour = cmds.add_parser("schema-retour", help="bring the database back to an older schema (v2)")
    retour.add_argument("--vers", type=int, required=True, choices=(2,), help="target schema version (2)")


def _filter_chantier(parser: argparse.ArgumentParser) -> None:
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--chantier", default=None, help="only the tasks of this chantier")
    group.add_argument("--hors-chantier", dest="hors_chantier", action="store_true",
                       help="only the tasks without a chantier")


def handle(args: argparse.Namespace, settings: Settings) -> dict[str, Any]:
    cmd = args.todo_command
    today = service.today_in(settings.todo_timezone)
    if cmd == "meta":
        return envelope(cmd, summary="todo options", data={
            "priorities": ["high", "normal", "low"], "categories": list(settings.todo_categories),
            "due": ["today", "tomorrow", "week", "none"], "timezone": settings.todo_timezone})

    if cmd == "schema-retour":  # before opening the store: opening would migrate a v2 base up to v3 first
        done = downgrade_to_v2(settings.todo_db)
        if not done["changed"]:
            return envelope(cmd, summary="base déjà en v2, rien à faire", data=done)
        summary = f"base ramenée de v3 à v2 ({done['method']}, SQLite {done['sqlite_version']}), copie {done['backup']}"
        journal.record(settings, "ultron-hub", "todo", f"Base des todos : {summary}")
        return envelope(cmd, summary=summary, data=done)

    with TodoStore(settings.todo_db) as store:
        if cmd == "add":
            category = service.parse_category(args.category or settings.todo_categories[0],
                                              settings.todo_categories)
            mode = getattr(args, "title_mode", None) or "reject"
            try:
                title_result = resolve_title(args.title, existing_notes=args.notes or None,
                                             mode=mode, summarizer=summarizer.llm_title)
            except TitleTooLongError as exc:
                msg = (f"Titre trop long : {exc.length} > {exc.limit}. "
                       "Utilisez --long (résumé LLM) ou --truncate.")
                return envelope(cmd, status="error", summary="titre trop long", error=msg)
            except EmptyTitleError as exc:
                return envelope(cmd, status="error", summary="titre vide", error=str(exc))
            actual_title = title_result.title
            actual_notes = title_result.notes if title_result.notes is not None else (args.notes or "")
            data_extra = {}
            squad_chantier = _squad_chantier()
            default_nature = "chantier" if squad_chantier else "fond"  # a squad's todos are chantiers (todo #105)
            if title_result.source != "as_is":
                data_extra["title_source"] = title_result.source
            task = store.add(actual_title, category=category, priority=service.parse_priority(args.priority),
                             due_date=service.parse_due(args.due, today), notes=actual_notes,
                             source=args.source, nature=service.parse_nature(args.nature or default_nature),
                             clair=args.clair or "",
                             chantier=service.parse_chantier(args.chantier) if args.chantier else squad_chantier)
            if args.clair is None:  # best effort: a failed generation never blocks the creation
                service.fill_clair(store, [task], lambda t: summarizer.llm_clair(t.title, t.notes))
                task = store.get(task.id)
            journal.record(settings, "ultron-hub", "todo", f"Todo créée : {task.title} (par {args.source})", task.id)
            _tableaux(settings)
            result_data = task.to_dict()
            result_data.update(data_extra)
            return envelope(cmd, summary=f"ajoutée : {service.format_line(task)}", data=result_data)

        if cmd == "list":
            status = None if args.status == "all" else args.status
            category = service.parse_category(args.category, settings.todo_categories) if args.category else None
            nature = service.parse_nature(args.nature) if args.nature else None
            tasks = store.list(status=status, category=category, limit=args.limit, nature=nature,
                               chantier=_chantier_filter(args), hors_chantier=args.hors_chantier)
            text = "\n".join(service.format_line(t) for t in tasks) or "aucune tâche"
            return envelope(cmd, summary=f"{len(tasks)} tâche(s)",
                            data={"tasks": [t.to_dict() for t in tasks], "text": text})

        if cmd == "show":
            task = store.get(args.id)
            return envelope(cmd, summary=service.format_line(task),
                            data={**task.to_dict(), "history": store.history(args.id),
                                  "branch": links.branch_map(settings).get(task.id)})

        if cmd == "board":
            return _board(args, settings, store, today)

        if cmd in ("done", "reopen", "cancel"):
            status = {"done": "done", "reopen": "todo", "cancel": "cancelled"}[cmd]
            task = store.get(args.id)
            verb = {"done": "Terminer", "reopen": "Rouvrir", "cancel": "Annuler"}[cmd]
            by = closing.authorize(cmd, task.id, human=getattr(args, "human", False), required=cmd != "reopen",
                                   what=f"{verb} la tâche {service.format_line(task)} ?",
                                   used=lambda proof: store.proof_used(task.id, proof))
            task = store.set_status(args.id, status, by=by)
            label = {"done": "terminée", "reopen": "rouverte", "cancel": "annulée"}[cmd]
            journal.record(settings, "ultron-hub", "todo", f"Todo {label} : {task.title} ({by.get('by')})", task.id)
            _tableaux(settings)
            return envelope(cmd, summary=f"{label} : {service.format_line(task)}", data=task.to_dict())

        if cmd == "close-auto":
            by = closing.verify_auto_close(settings, store, args.id)
            task = store.set_status(args.id, "done", by=by)
            journal.record(settings, "ultron-hub", "todo",
                           f"Todo terminée seule (fusionnée et vérifiée, {by['proof']}) : {task.title}", task.id)
            _tableaux(settings)
            return envelope(cmd, summary=f"terminée seule (fusion {by['proof']} vérifiée) : {service.format_line(task)}",
                            data={**task.to_dict(), "by": by})

        if cmd == "livree":
            note = service.parse_livree_note(args.note)
            task = store.mark_delivered(args.id, by="cli", note=note)
            journal.record(settings, "ultron-hub", "todo", f"Todo livrée : {task.title}", task.id)
            return envelope(cmd, summary=f"livrée, en attente de ton ✅ : {service.format_line(task)}",
                            data={**task.to_dict(), "livree": True, "note": note})

        if cmd == "edit":
            fields: dict[str, Any] = {}
            if args.title is not None:
                fields["title"] = args.title
            if args.priority is not None:
                fields["priority"] = service.parse_priority(args.priority)
            if args.category is not None:
                fields["category"] = service.parse_category(args.category, settings.todo_categories)
            if args.due is not None:
                fields["due_date"] = service.parse_due(args.due, today)
            if args.notes is not None:
                fields["notes"] = args.notes
            if args.nature is not None:
                fields["nature"] = service.parse_nature(args.nature)
            if args.clair is not None:
                fields["clair"] = args.clair
            if args.chantier is not None:
                fields["chantier"] = service.parse_chantier(args.chantier)
            elif args.sans_chantier:
                fields["chantier"] = None
            if not re.fullmatch(r"[a-z0-9:_-]{1,40}", args.by):
                raise InvalidRequestError("--by must match [a-z0-9:_-]{1,40}")
            before = store.get(args.id)
            task = store.update(args.id, by=args.by, **fields)
            if task.nature != before.nature:
                journal.record(settings, "ultron-hub", "todo", service.nature_journal_text(task), task.id)
            if task.chantier != before.chantier:
                journal.record(settings, "ultron-hub", "todo", service.chantier_journal_text(task), task.id)
            return envelope(cmd, summary=f"modifiée : {service.format_line(task)}", data=task.to_dict())

        if cmd == "rattacher":
            return _rattacher(args, settings, store)

        if cmd == "digest":
            open_tasks = store.list(status="todo", limit=1000)
            filled = service.fill_clair(store, open_tasks, lambda t: summarizer.llm_clair(t.title, t.notes))
            if filled:
                open_tasks = store.list(status="todo", limit=1000)
            digest = service.build_digest(open_tasks, today, _atoi_counts(settings))
            digest["clair_filled"] = filled
            etat.refresh(settings)
            if args.send:
                service.send_message(digest["text"], settings.todo_notify_target, settings.hermes_binary)
            digest["sent"] = bool(args.send)
            return envelope(cmd, summary=f"{digest['overdue']} en retard, {digest['today']} aujourd'hui",
                            data=digest)

    raise AssertionError(f"unhandled todo command: {cmd}")


def _tableaux(settings: Settings) -> None:
    """Refresh the pinned boards of the group topics (todo #202): direct mode only, never blocks the command."""
    try:
        from ultron_hub.groupe import tableau
        tableau.rafraichir(settings)
    except Exception:  # noqa: BLE001
        pass


def _rattacher(args: argparse.Namespace, settings: Settings, store: TodoStore) -> dict[str, Any]:
    if not re.fullmatch(r"[a-z0-9:_-]{1,40}", args.by):
        raise InvalidRequestError("--by must match [a-z0-9:_-]{1,40}")
    lines = service.propose_rattachement(store.list(status="todo", limit=BOARD_LIMIT), service.known_chantiers())
    fingerprint = service.rattachement_fingerprint(lines)
    chantiers = len({line["vers"] for line in lines if line["vers"]})
    if args.proposer:
        return envelope("rattacher", summary=f"{len(lines)} todo(s) à ranger dans {chantiers} chantier(s)",
                        data={"lines": lines, "empreinte": fingerprint, "chantiers": chantiers})
    if args.appliquer != fingerprint:
        raise InvalidRequestError(f"la proposition a changé (empreinte {fingerprint}, pas {args.appliquer}) : "
                                  "rien n'a été modifié, relis la proposition")
    for line in lines:
        before = store.get(line["id"])
        task = store.update(line["id"], by=args.by, chantier=line["vers"])
        if task.chantier != before.chantier:
            journal.record(settings, "ultron-hub", "todo", service.chantier_journal_text(task), task.id)
    return envelope("rattacher", summary=f"{len(lines)} todo(s) rangée(s) dans {chantiers} chantier(s)",
                    data={"lines": lines, "empreinte": fingerprint, "chantiers": chantiers})


def _squad_chantier() -> str | None:
    """The subject of the squad this command runs in (env set by the retired squad engine), when it is a known chantier.
    Best effort: an unknown or malformed value never blocks the creation, the todo is then outside any chantier."""
    value = os.environ.get(SQUAD_SUBJECT_ENV, "").strip()
    if not value:
        return None
    try:
        return service.parse_chantier(value)
    except Exception:
        log.warning("%s=%r is not a known chantier: todo created without chantier", SQUAD_SUBJECT_ENV, value)
        return None


def _chantier_filter(args: argparse.Namespace) -> str | None:
    """`--chantier` as a filter: well-formed is enough (the subject of a deleted prompt can still be looked up)."""
    return service.parse_chantier(args.chantier, must_exist=False) if args.chantier else None


def _atoi_counts(settings: Settings) -> dict[str, int] | None:
    """Items waiting for the user, by icon (todo #164). None if À toi cannot be read: the digest still goes out."""
    from ultron_hub.chantier import core as chantier_core  # lazy: chantier imports the todo package
    try:
        items = chantier_core.atoi(settings, chantier_core.sources())["items"]
    except Exception as exc:  # noqa: BLE001 — the morning message must never fail on this line
        log.warning("digest: À toi illisible (%s)", type(exc).__name__)
        return None
    counts: dict[str, int] = {}
    for kind in chantier_core.KINDS:
        n = sum(it["kind"] == kind for it in items)
        if n:
            icon = chantier_core.ICONS[kind]
            counts[icon] = counts.get(icon, 0) + n
    return counts


def _local_day(stamp: str | None, tz: ZoneInfo):
    """The local date of a stored UTC timestamp, None when absent or unreadable."""
    try:
        return datetime.fromisoformat(stamp).astimezone(tz).date() if stamp else None
    except ValueError:
        return None


def _board(args: argparse.Namespace, settings: Settings, store: TodoStore, today) -> dict[str, Any]:
    category = service.parse_category(args.category, settings.todo_categories) if args.category else None
    open_tasks = store.list(status="todo", limit=BOARD_LIMIT)
    fond = [t for t in open_tasks if t.nature == "fond"]
    overdue = [t for t in open_tasks if t.due_date and t.due_date < today.isoformat()]
    if args.filter == "closed":
        only = dict(chantier=_chantier_filter(args), hors_chantier=args.hors_chantier)
        closed = store.list(status="done", category=category, limit=BOARD_LIMIT, **only)
        closed += store.list(status="cancelled", category=category, limit=BOARD_LIMIT, **only)
        tasks = sorted(closed, key=lambda t: t.updated_at or "", reverse=True)[:CLOSED_LIMIT]
    elif args.filter == "done_today":  # todo #270: done today (todo timezone), most recent first
        tz = ZoneInfo(settings.todo_timezone)
        done = store.list(status="done", category=category, limit=BOARD_LIMIT)
        tasks = sorted((t for t in done if _local_day(t.done_at, tz) == today), key=lambda t: t.done_at or "", reverse=True)
    else:
        tasks = [t for t in open_tasks if category is None or t.category == category]
        if args.hors_chantier:
            tasks = [t for t in tasks if t.chantier is None]
        elif args.chantier:
            tasks = [t for t in tasks if t.chantier == _chantier_filter(args)]
        if args.filter == "fond":
            tasks = [t for t in tasks if t.nature == "fond"]
        elif args.filter == "open" and category is None and not (args.chantier or args.hors_chantier):
            # the main list: "en tête" todos, fond behind one button (a chantier's own list shows both)
            tasks = [t for t in tasks if t.nature == "chantier"]
        if args.filter == "urgent":
            tasks = [t for t in tasks if t.due_date and t.due_date <= today.isoformat()]
        tasks.sort(key=lambda t: service.board_rank(t, today))
    branch_map = links.branch_map(settings)
    rows = []
    for t in tasks:
        rows.append({**t.to_dict(), "overdue": bool(t.due_date and t.due_date < today.isoformat()
                                                   and t.status == "todo"),
                     "today": t.due_date == today.isoformat(),
                     "badges": links.badges(branch_map.get(t.id))})
    return envelope("board", summary=f"{len(rows)} tâche(s)", data={
        "filter": args.filter, "category": category, "chantier": _chantier_filter(args),
        "hors_chantier": args.hors_chantier, "tasks": rows, "open": len(open_tasks),
        "fond": len(fond), "chantiers": len(open_tasks) - len(fond),
        "overdue": len(overdue), "today": sum(t.due_date == today.isoformat() for t in open_tasks),
        "high": sum(t.priority == "high" for t in open_tasks),
        "branches": sum(bool(branch_map.get(t.id, {}).get("ahead")) for t in open_tasks),
        "categories": list(settings.todo_categories)})
